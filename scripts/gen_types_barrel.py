#!/usr/bin/env python3
"""Generate the ts-rs contract barrel (``packages/webui/src/types/index.ts``).

ts-rs writes one binding file per ``#[ts(export)]`` type but no barrel,
and a hand-maintained ``index.ts`` drifts silently: a newly exported type
lands as a file nobody re-exports (green build, unreachable binding).
This script derives the barrel FROM DISK — enumerate the binding files,
emit one ``export type { X } from "./X.ts"`` line per file, sorted — so
``just webui-types`` can never leave the two sets out of bijection.

It also VALIDATES the bijection when ``--check`` is given: an index.ts
whose re-export set differs from the disk set (a hand edit, a stale
commit) fails with a non-zero exit instead of being rewritten, so CI can
use it as a hard gate.

Usage:
    python3 scripts/gen_types_barrel.py            # write index.ts
    python3 scripts/gen_types_barrel.py --check    # verify only, exit 1 on drift
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES_DIR = ROOT / "packages" / "webui" / "src" / "types"
BARREL = TYPES_DIR / "index.ts"

_HEADER = """/**
 * The ts-rs contract barrel (Rust → TS, one direction).
 *
 * GENERATED by `just webui-types` (ts-rs export tests + this barrel —
 * see scripts/gen_types_barrel.py). Every binding file here is generated
 * by `cargo test -p i0721-proto -p i0721-server`; never hand-edit this
 * file or the bindings. Regenerate with `just webui-types` and commit.
 */
"""

_EXPORT_RE = re.compile(r'^export type \{ ([A-Za-z0-9_]+) \} from "\./([A-Za-z0-9_]+)\.ts";$')


def binding_files() -> list[Path]:
    """The ts-rs binding files on disk (barrel excluded), sorted by name."""
    return sorted(
        (p for p in TYPES_DIR.glob("*.ts") if p.name != BARREL.name),
        key=lambda p: p.name,
    )


def render_barrel(paths: list[Path]) -> str:
    lines = [_HEADER]
    for path in paths:
        lines.append(f'export type {{ {path.stem} }} from "./{path.stem}.ts";\n')
    return "".join(lines)


def parse_barrel(text: str) -> set[str]:
    """The re-exported names in an existing barrel (one per line)."""
    names: set[str] = set()
    for line in text.splitlines():
        m = _EXPORT_RE.match(line.strip())
        if m:
            names.add(m.group(1))
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed barrel matches the disk file set; exit 1 on drift",
    )
    args = parser.parse_args()

    paths = binding_files()
    disk_names = {p.stem for p in paths}
    expected = render_barrel(paths)

    if args.check:
        current = BARREL.read_text(encoding="utf-8") if BARREL.is_file() else ""
        exported = parse_barrel(current)
        missing = disk_names - exported
        extra = exported - disk_names
        stale = "" if current == expected else " (content differs from the generated form)"
        if missing or extra or stale:
            for name in sorted(missing):
                print(f"[FAIL] barrel is missing the re-export for {name}.ts", file=sys.stderr)
            for name in sorted(extra):
                print(f"[FAIL] barrel re-exports {name}, which has no binding file", file=sys.stderr)
            if stale and not (missing or extra):
                print(f"[FAIL] barrel content drifted from the generated form{stale}", file=sys.stderr)
            print("regenerate with `just webui-types` and commit", file=sys.stderr)
            return 1
        print(f"[ OK ] barrel matches the {len(disk_names)} binding files")
        return 0

    BARREL.write_text(expected, encoding="utf-8")
    print(f"wrote {BARREL.relative_to(ROOT)} ({len(paths)} bindings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
